import { z } from 'zod';
import { plainText } from '../../utils/sanitize.js';
import { MAX_AMOUNT } from '../../utils/money.js';

/** Money arrives as a string or number; we validate format strictly and keep it as a string. */
export const moneyInput = z
  .union([z.string(), z.number()])
  .transform((v) => String(v).trim())
  .refine((v) => /^\d{1,12}(\.\d{1,2})?$/.test(v), 'Must be a positive amount with at most 2 decimal places')
  .refine((v) => Number(v) > 0, 'Must be greater than zero')
  .refine((v) => Number(v) <= MAX_AMOUNT.toNumber(), `Must not exceed ${MAX_AMOUNT.toFixed(0)}`);

const isoDate = z.coerce.date().refine((d) => !Number.isNaN(d.getTime()), 'Invalid date');
const imageUrls = z.array(z.string().max(500)).max(8, 'At most 8 images');

export const createAuctionSchema = z.object({
  title: z.string().transform(plainText).pipe(z.string().min(3, 'Title is too short').max(120)),
  description: z.string().transform(plainText).pipe(z.string().min(10, 'Description is too short').max(5000)),
  categoryId: z.coerce.number().int().positive(),
  startingPrice: moneyInput,
  minimumBidIncrement: moneyInput,
  startTime: isoDate,
  endTime: isoDate,
  imageUrls: imageUrls.default([]),
  publish: z.boolean().default(false),
});
export type CreateAuctionBody = z.infer<typeof createAuctionSchema>;

export const updateAuctionSchema = createAuctionSchema.omit({ publish: true }).partial().refine((b) => Object.keys(b).length > 0, 'Nothing to update');
export type UpdateAuctionBody = z.infer<typeof updateAuctionSchema>;

export const cancelSchema = z.object({
  reason: z.string().transform(plainText).pipe(z.string().min(5, 'Please give a reason (at least 5 characters)').max(500)),
});

export const browseSchema = z.object({
  q: z.string().trim().max(100).optional().transform((v) => (v ? v : undefined)),
  category: z.string().trim().max(60).optional(),
  status: z.enum(['ACTIVE', 'SCHEDULED', 'COMPLETED', 'ALL']).default('ACTIVE'),
  minPrice: z.coerce.number().min(0).max(MAX_AMOUNT.toNumber()).optional(),
  maxPrice: z.coerce.number().min(0).max(MAX_AMOUNT.toNumber()).optional(),
  sort: z.enum(['ending_soon', 'newest', 'price_asc', 'price_desc', 'most_bids']).default('ending_soon'),
  featured: z
    .enum(['true', 'false'])
    .optional()
    .transform((v) => v === 'true'),
  sellerId: z.coerce.number().int().positive().optional(),
  page: z.coerce.number().int().min(1).max(1000).default(1),
  pageSize: z.coerce.number().int().min(1).max(48).default(12),
});
export type BrowseQuery = z.infer<typeof browseSchema>;

export const placeBidSchema = z.object({
  amount: z.union([z.string(), z.number()]).transform((v) => String(v).trim()),
  // UUID generated by the client per bid attempt; reused verbatim on retries of the same attempt.
  clientRequestId: z.string().trim().min(8).max(64).regex(/^[A-Za-z0-9-]+$/, 'clientRequestId must be alphanumeric/UUID'),
});
